CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  revision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS tasks (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  title VARCHAR(120) NOT NULL,
  due_at VARCHAR(16) NOT NULL,
  minutes INTEGER NOT NULL,
  priority INTEGER NOT NULL,
  done INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS windows (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  title VARCHAR(120) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  start_at VARCHAR(16) NOT NULL,
  end_at VARCHAR(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS interests (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  title VARCHAR(120) NOT NULL,
  category VARCHAR(16) NOT NULL,
  minutes INTEGER NOT NULL,
  progress VARCHAR(16) NOT NULL,
  session_note VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS blocks (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  kind VARCHAR(16) NOT NULL,
  item_id INTEGER NOT NULL,
  title VARCHAR(120) NOT NULL,
  start_at VARCHAR(16) NOT NULL,
  end_at VARCHAR(16) NOT NULL
);
CREATE TABLE IF NOT EXISTS activities (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  user_id INTEGER NOT NULL REFERENCES users(id),
  kind VARCHAR(16) NOT NULL,
  log_day VARCHAR(10) NOT NULL,
  minutes INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS day_choices (
  user_id INTEGER NOT NULL REFERENCES users(id),
  plan_day VARCHAR(10) NOT NULL,
  mode VARCHAR(16) NOT NULL,
  routine VARCHAR(16) NOT NULL,
  prompt_hidden INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, plan_day)
);
CREATE TABLE IF NOT EXISTS goals (
  user_id INTEGER PRIMARY KEY REFERENCES users(id),
  reading_sessions INTEGER NOT NULL,
  busy_days INTEGER NOT NULL,
  rest_minutes INTEGER NOT NULL,
  gaming_minutes INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS feedback (
  user_id INTEGER NOT NULL REFERENCES users(id),
  plan_day VARCHAR(10) NOT NULL,
  item_key VARCHAR(40) NOT NULL,
  decision VARCHAR(12) NOT NULL,
  until_at VARCHAR(16) NOT NULL,
  PRIMARY KEY (user_id, plan_day, item_key)
);
